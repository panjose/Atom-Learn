def run(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    if args.action == "capsule":
        from capsule import CapsuleError, run as run_capsule

        try:
            run_capsule(["--help"] if args.capsule_help else args.capsule_args)
        except (CapsuleError, PlatformStateError, OSError, json.JSONDecodeError, yaml.YAMLError) as exc:
            raise EvolutionError(str(exc)) from exc
        return
    engine = EvolutionEngine.load(args.workspace)
    if args.action != "validate":
        existing_errors = engine.validate()
        if existing_errors:
            raise EvolutionError(
                "Refusing to use invalid evolution state; run evolve validate and repair it first:\n- "
                + "\n- ".join(existing_errors)
            )
    if args.action == "status":
        print(json.dumps(engine.status_summary(), ensure_ascii=False, indent=2))
        return
    if args.action == "validate":
        errors = engine.validate()
        if errors:
            raise EvolutionError("Evolution validation failed:\n- " + "\n- ".join(errors))
        print(json.dumps({"ok": True, "evolution_revision": engine.revision}, indent=2))
        return
    if args.action == "list":
        proposals = engine.proposals()
        if args.status:
            proposals = [item for item in proposals if item.get("status") == args.status]
        print(json.dumps(proposals, ensure_ascii=False, indent=2))
        return
    if args.action == "policy":
        print(json.dumps(engine.policy, ensure_ascii=False, indent=2))
        return
    if args.action == "preview":
        print(json.dumps(engine.preview(args.proposal_id), ensure_ascii=False, indent=2))
        return
    engine.expect_revision(args.expected_evolution_revision)
    if args.action == "analyze":
        result = engine.analyze(args.propose)
    elif args.action == "propose":
        result = engine.create_proposal(read_data(Path(args.input)))
    elif args.action == "approve":
        result = engine.approve(args.proposal_id, args.authority, args.actor)
    elif args.action == "reject":
        result = engine.reject(args.proposal_id, args.reason)
    elif args.action == "apply":
        result = engine.apply(args.proposal_id)
    elif args.action == "monitor":
        result = engine.monitor(args.proposal_id)
    elif args.action == "rollback":
        result = engine.rollback(args.proposal_id, args.reason)
    else:  # pragma: no cover
        raise EvolutionError(f"Unhandled evolution action: {args.action}")
    output = {
        "ok": True,
        "evolution_revision": engine.revision,
        "course_revision": engine.workspace.revision,
        "result": result,
    }
    print(json.dumps(output, ensure_ascii=False, indent=2))


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")
    try:
        run(argv)
        return 0
    except (EvolutionError, AtomLearnError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
