def test_blocking_backtrack_returns_to_parent() -> None:
    workspace, revision = new_workspace("backtrack")
    revision = activate(workspace, "calculus.limit.approach", revision)
    revision, result = assess_once(workspace, "calculus.limit.approach", revision, 0.9)
    assert result == "mastered"
    revision = activate(workspace, "calculus.rate.average", revision)
    question_payload = write_payload(
        workspace,
        "blocking.yaml",
        {
            "text": "趋近和等于的区别会不会影响这里？",
            "classification": "blocking_prerequisite",
            "related_atom_id": "calculus.limit.approach",
            "rationale": "The learner needs to revisit the distinction before continuing.",
            "priority": "high",
        },
    )
    question = output_json(
        invoke("record-question", workspace, "--input", question_payload, "--expected-revision", revision)
    )
    backtracked = output_json(
        invoke(
            "backtrack",
            workspace,
            "--to",
            "calculus.limit.approach",
            "--question-id",
            question["question_id"],
            "--expected-revision",
            question["revision"],
        )
    )
    assert backtracked["active_atom_id"] == "calculus.limit.approach"
    revision, result = assess_once(
        workspace,
        "calculus.limit.approach",
        backtracked["revision"],
        0.9,
        kind="review",
    )
    assert result == "mastered"
    resumed = output_json(invoke("resume", workspace, "--expected-revision", revision))
    assert resumed["active_atom_id"] == "calculus.rate.average"
    state = status(workspace)
    assert state["session"]["backtrack_stack"] == []
    assert state["session"]["phase"] == "questioning"


def test_restructure_requires_confirmation_and_preserves_alias() -> None:
    workspace, revision = new_workspace("restructure")
    proposal = write_payload(
        workspace,
        "split.yaml",
        {
            "action": "split",
            "source_atom_id": "calculus.limit.approach",
            "downstream_replacement_id": "calculus.limit.distinguish",
            "new_atoms": [
                {
                    "id": "calculus.limit.sequence-intuition",
                    "title": "序列趋近的直觉",
                    "module": "Limits",
                    "objective": "解释序列逐步逼近一个值",
                    "prerequisites": [],
                    "mastery": {
                        "required_dimensions": ["explain"],
                        "pass_threshold": 0.8,
                        "minimum_dimension_score": 0.6,
                    },
                },
                {
                    "id": "calculus.limit.distinguish",
                    "title": "趋近与取到的辨析",
                    "module": "Limits",
                    "objective": "辨析趋近与实际取值",
                    "prerequisites": ["calculus.limit.sequence-intuition"],
                    "mastery": {
                        "required_dimensions": ["explain", "discriminate"],
                        "pass_threshold": 0.8,
                        "minimum_dimension_score": 0.6,
                    },
                },
            ],
        },
    )
    preview = output_json(
        invoke("restructure", workspace, "--proposal", proposal, "--expected-revision", revision)
    )
    assert preview["applied"] is False
    assert status(workspace)["course"]["revision"] == revision

    applied = output_json(
        invoke(
            "restructure",
            workspace,
            "--proposal",
            proposal,
            "--confirmed",
            "--expected-revision",
            revision,
        )
    )
    assert applied["applied"] is True
    graph = yaml.safe_load((workspace / ".atomlearn" / "graph.yaml").read_text(encoding="utf-8"))
    assert graph["aliases"]["calculus.limit.approach"] == "calculus.limit.distinguish"
    archived = yaml.safe_load(
        (workspace / ".atomlearn" / "atoms" / "calculus.limit.approach.yaml").read_text(encoding="utf-8")
    )
    assert archived["status"] == "archived"
    assert output_json(invoke("validate", workspace))["ok"] is True


def test_single_atom_course_completes_and_revision_mismatch_is_detected() -> None:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    workspace = RUN_ROOT / f"completion-{uuid.uuid4().hex}"
    output_json(
        invoke(
            "init",
            workspace,
            "--course-id",
            "test.completion",
            "--title",
            "One Atom",
            "--goal",
            "Finish one observable objective",
        )
    )
    plan = write_payload(
        workspace,
        "plan.yaml",
        {
            "atoms": [
                {
                    "id": "one.atom",
                    "title": "One Atom",
                    "objective": "Explain and apply one idea",
                    "prerequisites": [],
                    "mastery": {
                        "required_dimensions": ["explain", "apply"],
                        "pass_threshold": 0.8,
                        "minimum_dimension_score": 0.6,
                    },
                }
            ]
        },
    )
    revision = output_json(
        invoke("import-plan", workspace, "--input", plan, "--expected-revision", 0)
    )["revision"]
    revision = activate(workspace, "one.atom", revision)
    revision, result = assess_once(workspace, "one.atom", revision, 0.9)
    assert result == "mastered"
    assert status(workspace)["course"]["status"] == "completed"

    current_path = workspace / ".atomlearn" / "state" / "current.yaml"
    current = yaml.safe_load(current_path.read_text(encoding="utf-8"))
    current["revision"] = revision + 1
    current_path.write_text(yaml.safe_dump(current, sort_keys=False), encoding="utf-8")
    invalid = invoke("validate", workspace, check=False)
    assert invalid.returncode == 2
    assert "does not match course.revision" in invalid.stderr
