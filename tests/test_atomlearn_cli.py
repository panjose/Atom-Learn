from __future__ import annotations

import json
import subprocess
import sys
import uuid
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / "atom-learn" / "scripts" / "atomlearn.py"
CALCULUS_PLAN = ROOT / "examples" / "calculus-mini" / "plan.yaml"
OS_PLAN = ROOT / "examples" / "operating-systems-mini" / "plan.yaml"
RUN_ROOT = ROOT / ".test-workspaces"


def invoke(*args: object, check: bool = True) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(
        [sys.executable, str(CLI), *(str(arg) for arg in args)],
        cwd=ROOT,
        text=True,
        encoding="utf-8",
        capture_output=True,
        check=False,
    )
    if check and result.returncode != 0:
        raise AssertionError(f"command failed: {result.args}\nstdout={result.stdout}\nstderr={result.stderr}")
    return result


def output_json(result: subprocess.CompletedProcess[str]) -> dict:
    return json.loads(result.stdout)


def new_workspace(label: str, plan: Path = CALCULUS_PLAN) -> tuple[Path, int]:
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    workspace = RUN_ROOT / f"{label}-{uuid.uuid4().hex}"
    output_json(
        invoke(
            "init",
            workspace,
            "--course-id",
            f"test.{label}",
            "--title",
            f"Test {label}",
            "--goal",
            "Exercise AtomLearn deterministically",
        )
    )
    imported = output_json(invoke("import-plan", workspace, "--input", plan, "--expected-revision", 0))
    return workspace, imported["revision"]


def write_payload(workspace: Path, name: str, payload: dict) -> Path:
    path = workspace / name
    path.write_text(yaml.safe_dump(payload, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return path


def status(workspace: Path) -> dict:
    return output_json(invoke("status", workspace, "--json"))


def activate(workspace: Path, atom_id: str, revision: int) -> int:
    return output_json(
        invoke("activate", workspace, atom_id, "--expected-revision", revision)
    )["revision"]


def evidence_payload(atom_id: str, score: float, kind: str = "mastery_check") -> dict:
    return {
        "atom_id": atom_id,
        "kind": kind,
        "prompt": "Explain and apply the current idea, then address its main misconception.",
        "response_summary": "The learner produced a concise explanation and a worked response.",
        "scores": {"explain": score, "apply": score, "discriminate": score},
        "feedback": "The response was evaluated against the declared dimensions.",
        "rationale": "The score records observable performance rather than self-reported confidence.",
    }


def assess_once(
    workspace: Path,
    atom_id: str,
    revision: int,
    score: float,
    *,
    kind: str = "mastery_check",
    now: str = "2026-01-01T00:00:00+00:00",
) -> tuple[int, str]:
    payload = write_payload(workspace, f"evidence-{uuid.uuid4().hex}.yaml", evidence_payload(atom_id, score, kind))
    recorded = output_json(
        invoke("record-evidence", workspace, "--input", payload, "--expected-revision", revision)
    )
    assessed = output_json(
        invoke(
            "assess",
            workspace,
            atom_id,
            "--evidence-id",
            recorded["evidence_id"],
            "--now",
            now,
            "--expected-revision",
            recorded["revision"],
        )
    )
    return assessed["revision"], assessed["result"]


def test_init_import_validate_render_and_status() -> None:
    workspace, revision = new_workspace("orientation")
    validated = output_json(invoke("validate", workspace))
    assert validated == {"ok": True, "revision": revision, "atoms": 5}

    state = status(workspace)
    assert state["session"]["active_atom_id"] is None
    assert state["counts"] == {"available": 2, "locked": 3}
    assert {item["id"] for item in state["next_candidates"]} == {
        "calculus.limit.approach",
        "calculus.rate.average",
    }
    for filename in ["LEARNING_MAP.md", "CURRENT.md", "PROGRESS.md", "QUESTIONS.md", "SOURCES.md"]:
        text = (workspace / filename).read_text(encoding="utf-8")
        assert "Generated by AtomLearn" in text


def test_mastery_requires_evidence_and_unlocks_successors() -> None:
    workspace, revision = new_workspace("mastery")
    revision = activate(workspace, "calculus.limit.approach", revision)

    revision, result = assess_once(workspace, "calculus.limit.approach", revision, 0.55)
    assert result == "partial"
    state = status(workspace)
    assert state["active_atom"]["id"] == "calculus.limit.approach"
    assert state["session"]["next_action"].startswith("Remediate")

    revision, result = assess_once(workspace, "calculus.limit.approach", revision, 0.9)
    assert result == "mastered"
    state = status(workspace)
    assert state["session"]["active_atom_id"] is None
    assert state["counts"]["mastered"] == 1
    assert len(yaml.safe_load((workspace / ".atomlearn" / "reviews.yaml").read_text(encoding="utf-8"))["items"]) == 1

    stale = invoke(
        "activate",
        workspace,
        "calculus.rate.average",
        "--expected-revision",
        revision - 1,
        check=False,
    )
    assert stale.returncode == 2
    assert "Stale revision" in stale.stderr


def test_future_question_is_parked_without_changing_focus() -> None:
    workspace, revision = new_workspace("questions", OS_PLAN)
    revision = activate(workspace, "os.program.definition", revision)
    payload = write_payload(
        workspace,
        "question.yaml",
        {
            "text": "那线程是什么？",
            "classification": "future_atom",
            "related_atom_id": "os.thread.definition",
            "rationale": "Threads have their own mapped Atom after process context.",
            "priority": "normal",
        },
    )
    recorded = output_json(
        invoke("record-question", workspace, "--input", payload, "--expected-revision", revision)
    )
    state = status(workspace)
    assert state["session"]["active_atom_id"] == "os.program.definition"
    assert state["session"]["phase"] == "teaching"
    question = next(item for item in state["open_questions"] if item["id"] == recorded["question_id"])
    assert question["status"] == "parked"
    assert question["related_atom_id"] == "os.thread.definition"


def test_evidence_can_be_recorded_only_for_the_active_atom() -> None:
    workspace, revision = new_workspace("evidence-guard")
    available_payload = write_payload(
        workspace,
        "available-evidence.yaml",
        evidence_payload("calculus.limit.approach", 0.9),
    )
    without_active = invoke(
        "record-evidence",
        workspace,
        "--input",
        available_payload,
        "--expected-revision",
        revision,
        check=False,
    )
    assert without_active.returncode == 2
    assert "only for the Active Atom" in without_active.stderr

    revision = activate(workspace, "calculus.limit.approach", revision)
    locked_payload = write_payload(
        workspace,
        "locked-evidence.yaml",
        evidence_payload("calculus.derivative.definition", 0.9),
    )
    for_locked = invoke(
        "record-evidence",
        workspace,
        "--input",
        locked_payload,
        "--expected-revision",
        revision,
        check=False,
    )
    assert for_locked.returncode == 2
    assert "requested 'calculus.derivative.definition'" in for_locked.stderr
    assert status(workspace)["course"]["revision"] == revision
    evidence = yaml.safe_load(
        (workspace / ".atomlearn" / "evidence.yaml").read_text(encoding="utf-8")
    )
    assert evidence["items"] == []
    assert output_json(invoke("validate", workspace))["ok"] is True


def test_due_review_can_be_activated() -> None:
    workspace, revision = new_workspace("review")
    revision = activate(workspace, "calculus.limit.approach", revision)
    revision, result = assess_once(workspace, "calculus.limit.approach", revision, 0.9)
    assert result == "mastered"
    refreshed = output_json(
        invoke(
            "refresh-reviews",
            workspace,
            "--now",
            "2026-01-03T00:00:00+00:00",
            "--expected-revision",
            revision,
        )
    )
    assert refreshed["due_atom_ids"] == ["calculus.limit.approach"]
    revision = activate(workspace, "calculus.limit.approach", refreshed["revision"])
    state = status(workspace)
    assert state["session"]["phase"] == "reviewing"
    assert state["active_atom"]["status"] == "active"
    assert revision == refreshed["revision"] + 1

    blocked = invoke(
        "skip",
        workspace,
        "calculus.limit.approach",
        "--mode",
        "defer",
        "--reason-code",
        "time_constraint",
        "--expected-revision",
        revision,
        check=False,
    )
    assert blocked.returncode == 2
    assert "already has mastered Evidence" in blocked.stderr
    assert status(workspace)["course"]["revision"] == revision


